const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

export async function* mockStream(agent: AgentId, lastUser: string, turns: number) {
  if (agent === "research") {
    yield { type: "status", text: "\"회사 인재상\" 검색 중" };
    await sleep(500);
    yield { type: "status", text: "채용공고 페이지 읽는 중" };
    await sleep(500);
  } else {
    yield { type: "status", text: "생각하는 중" };
    await sleep(400);
  }
  let text = SAMPLES[agent];
  if (agent === "reviser") text = text.replace("수정된 본문이에요.", `수정된 본문이에요. (${new Date().toLocaleTimeString("ko-KR")})`);
  if (agent === "interviewer" && lastUser.includes("[면접 종료]")) {
    text = `## 종합 점수: 68 / 100\n합격 가능성: 보통 (모의 응답)\n\n## 질문별 피드백\n**Q1. 자기소개** / 핵심이 늦게 나와요.\n\n## 다음 면접 전에 연습할 것\n1. 두괄식으로 답하기`;
  } else if (agent === "interviewer" && turns > 1) {
    const n = Math.floor(Math.random() * 5) + 2;
    text = `네, 잘 들었습니다. (모의 응답)\n\n**Q${n}.** 그 경험에서 본인이 맡은 역할을 조금 더 구체적으로 말씀해 주시겠어요?`;
  }
  for (const chunk of text.match(/[\s\S]{1,12}/g) ?? []) {
    yield { type: "text", text: chunk };
    await sleep(15);
  }
}

export function buildContextBlock(ctx: AgentContext): string {
  const parts: string[] = [];
  for (const key of Object.keys(CONTEXT_LABELS) as (keyof AgentContext)[]) {
    const v = ctx[key];
    if (typeof v === "string" && v.trim()) {
      const tag = CONTEXT_LABELS[key];
      parts.push(`<${tag}>\n${v.trim()}\n</${tag}>`);
    }
  }
  return parts.length ? `<참고_자료>\n${parts.join("\n\n")}\n</참고_자료>` : "<참고_자료>(없음)</참고_자료>";
}
